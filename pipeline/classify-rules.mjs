/**
 * 分类与标签的耦合不变量（代码层强制，不依赖提示词自觉）：
 * regions 是政策专属维度——全端只有政策语境消费它（政策tab标签条、
 * 政策卡片角标、国别标签页均限定 category=policy），非政策文章的国别
 * 语义混乱（公司国籍/事件发生地/不知所云）且构成死数据与详情页死链。
 * 分类不是 policy 时无条件清空 regions。
 * @param {string} category - 最终判定的分类
 * @param {Object} tags - normalizeTags 后的 tags 对象
 * @returns {Object} 应用不变量后的 tags（原对象不被修改）
 */
export function applyTagInvariants(category, tags) {
  const t = { ...tags };
  if (category !== 'policy') t.regions = [];
  return t;
}
